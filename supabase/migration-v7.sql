--
--  Что делает: заводит страховку «дня в ударе».
--   1. заряды щита — по одному на спасённый день, с восстановлением за работу;
--   2. привал — осознанная остановка счёта без ограничения по длине;
--   3. автосейв — тратить заряд самому, если день кончился без квоты.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- ЗАЧЕМ ЭТО ВООБЩЕ
--
--    Серия закрытых дней — самое дорогое, что копится в приложении, и самое
--    хрупкое: один вечер без сил обнуляет недели. Страх потерять серию
--    заставляет добивать квоту через отвращение, а действие, сделанное через
--    отвращение, закрепляется как наказание. Дальше человек перестаёт
--    открывать приложение — и теряет уже не серию, а привычку.
--
--    Щит стоит ровно столько, чтобы им нельзя было жить: три заряда, новый
--    за четыре закрытых дня. Привал не стоит ничего, но и не даёт ничего —
--    серия на нём замирает и не растёт ни дня.
--
--    Общее правило обоих: закрытая квота сильнее любой защиты. Сделал норму
--    в защищённый день — день засчитан как обычный, серия +1, заряд вернулся
--    в запас, привал снялся сам. За работу приложение не наказывает никогда.
-- ---------------------------------------------------------------------------
alter table public.profiles
  -- Доступные заряды щита. Стартовые три — чтобы страховка работала с
  -- первого же вечера, а не через две недели накопления.
  add column if not exists shield_charges  integer default 3,
  -- Закрытых дней в счёт следующего заряда, 0..3.
  add column if not exists shield_progress integer default 0,
  -- Логический день, на который щит взведён. null — щит не взведён.
  add column if not exists shield_date     date,
  -- Тратить заряд самому на границе суток. Включено: человек, у которого
  -- нет сил на рассылки, тем более не вспомнит нажать кнопку.
  add column if not exists shield_auto     boolean default true,
  -- День начала привала. null — привала нет.
  add column if not exists pause_start     date;

-- Старые профили создавались без этих колонок: default проставляется только
-- новым строкам, существующим нужно записать значения явно.
update public.profiles
   set shield_charges  = coalesce(shield_charges, 3),
       shield_progress = coalesce(shield_progress, 0),
       shield_auto     = coalesce(shield_auto, true)
 where shield_charges is null
    or shield_progress is null
    or shield_auto is null;

-- ---------------------------------------------------------------------------
-- ГРАНИЦЫ ЗНАЧЕНИЙ
--
--    Заряды и прогресс считает клиент, и ошибка в нём не должна превращаться
--    в бесконечный запас щитов. База держит рамку: 0..3 заряда и 0..3
--    закрытых дня в счёт следующего — четвёртый уже превращается в заряд.
-- ---------------------------------------------------------------------------
alter table public.profiles drop constraint if exists profiles_shield_charges_check;
alter table public.profiles
  add constraint profiles_shield_charges_check check (shield_charges between 0 and 3);

alter table public.profiles drop constraint if exists profiles_shield_progress_check;
alter table public.profiles
  add constraint profiles_shield_progress_check check (shield_progress between 0 and 3);

-- ---------------------------------------------------------------------------
-- ПРОВЕРКА
--
--    После Run в результате должна быть одна строка с тремя зарядами,
--    включённым автосейвом и пустыми полями щита и привала.
-- ---------------------------------------------------------------------------
select shield_charges,
       shield_progress,
       shield_date,
       shield_auto,
       pause_start,
       quota_streak,
       current_quota
  from public.profiles;

