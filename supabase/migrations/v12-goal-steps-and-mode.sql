-- ---------------------------------------------------------------------------
-- 1. ЭТАПЫ ЦЕЛИ
--
--    Сумма и срок — это факты, но между ними нет ни одного действия. Раньше
--    приложение пыталось заполнить этот разрыв прогнозом: переводило сумму
--    в число рассылок через среднюю конверсию. Для продюсирования это враньё:
--    один эксперт может дать два миллиона, а десять — ноль, и «до цели 1083
--    рассылки» не значит ничего.
--
--    Этапы человек пишет сам: закрыть эксперта, подписать договор, собрать
--    продукт, сделать запуск. Это единственная часть пути, которая зависит
--    от него, — и единственная, которую честно показывать как прогресс.
-- ---------------------------------------------------------------------------
alter table public.goals
  add column if not exists steps jsonb not null default '[]'::jsonb;

update public.goals set steps = '[]'::jsonb where steps is null;

-- ---------------------------------------------------------------------------
-- 2. РЕЖИМ: ШЕСТЬ СЧЁТЧИКОВ
--
--    Три уже были. Ключи существующих не трогаем: на них висит вся история.
-- ---------------------------------------------------------------------------
alter table public.profiles
  add column if not exists mode_flour_days integer default 0,
  add column if not exists mode_music_days integer default 0,
  add column if not exists mode_reels_days integer default 0;

update public.profiles
   set mode_flour_days = coalesce(mode_flour_days, 0),
       mode_music_days = coalesce(mode_music_days, 0),
       mode_reels_days = coalesce(mode_reels_days, 0)
 where mode_flour_days is null
    or mode_music_days is null
    or mode_reels_days is null;

-- ---------------------------------------------------------------------------
-- 3. СЧЁТ ПО УМОЛЧАНИЮ
--
--    Раньше счётчик двигал вечерний чекин: ответил «да» — плюс день, не
--    ответил — счётчик стоял. На практике чекин пропускается чаще, чем
--    делается, и счётчик замирал у человека, который на самом деле держался.
--    Замерший счётчик обесценивает выдержку ровно тем, что её не замечает.
--
--    Теперь наоборот: день засчитывается сам, а отмечать надо только срыв.
--    Это честнее по факту — сорвался ты или нет, знаешь только ты, и
--    единственное, о чём приложение обязано спросить, это про срыв.
--
--    mode_last_checkin меняет смысл: это последний день, за который счётчики
--    уже начислены. Старое значение подходит как есть.
-- ---------------------------------------------------------------------------
comment on column public.profiles.mode_last_checkin is
  'Последний день, за который счётчики режима уже начислены.';

-- ---------------------------------------------------------------------------
-- ПРОВЕРКА
-- ---------------------------------------------------------------------------
select
  mode_porn_days, mode_mb_days, mode_sugar_days,
  mode_flour_days, mode_music_days, mode_reels_days,
  mode_last_checkin,
  (select count(*) from public.goals) as goals
  from public.profiles;

