-- ---------------------------------------------------------------------------
-- ПЕРЕПИСКА ЦЕЛИКОМ РЯДОМ С КОНТАКТОМ
--
--    Формат: массив объектов [{"role":"me"|"them","text":"…"}, …] в порядке
--    сообщений. Отдельной таблицы нет намеренно: переписка читается и
--    пишется всегда целиком, а список рассылок грузится одним запросом —
--    join сюда добавил бы второй, ничего не дав взамен.
--
--    Оффер решает, ответят ли вообще. Дальше решает переписка: человек
--    ответил, разговор ушёл в монолог, последнее слово осталось за ним —
--    и контакт тихо умер. Чтобы это чинить, переписку надо где-то хранить.
-- ---------------------------------------------------------------------------
alter table public.outreach_contacts
  add column if not exists conversation jsonb not null default '[]'::jsonb;

-- Старые строки могли получить null до появления not null — подчищаем.
update public.outreach_contacts
   set conversation = '[]'::jsonb
 where conversation is null;

-- Частичный индекс: переписка есть у единиц контактов, а искать нужно
-- именно их. Сравнение с пустым массивом, а не jsonb_array_length(): длина
-- падает с ошибкой на значении, которое массивом не является, и одна такая
-- строка уронила бы построение индекса.
create index if not exists outreach_contacts_conversation_idx
  on public.outreach_contacts (user_id)
  where conversation <> '[]'::jsonb;

